"""Ask Memora intent classifier: sentence embeddings (all-MiniLM-L6-v2) + multinomial logistic regression,
with an out-of-scope threshold. Trained by training/train_intent.py on author-written example questions.

Answers are never generated by a language model: each intent maps to a template filled from Memora's
own records (memora/assistant.py), so the assistant cannot invent facts."""
import json
import re
import threading
from pathlib import Path

import numpy as np

from memora import config
from memora.ml import models

INTENTS = [
    "where_is_object",     # "where are my keys?"
    "medicine",            # "did I take my tablets?", "what medicine is next?"
    "today_schedule",      # "what do I have today?"
    "who_visited",         # "who came to see me today?"
    "who_is_person",       # "who is Rahul?"
    "orientation_time",    # "what day is it?"
    "orientation_place",   # "where am I?", "I want to go home"
    "need_help",           # "help me, I fell"
    "feeling",             # "I feel lonely"
    "out_of_scope",
]
ORIENTATION_INTENTS = {"orientation_time", "orientation_place"}

# Keyword rules: the evaluation baseline.
RULES = [
    ("need_help", r"\b(help|fell|fallen|hurt|emergency|ambulance)\b"),
    ("where_is_object", r"\b(where('s| is| are)? (is |are )?my|can'?t find|lost my|seen my|misplaced)\b"),
    ("medicine", r"\b(medicine|medication|tablet|tablets|pill|pills|dose)\b"),
    ("who_visited", r"\b(visit|visited|came to see|who came)\b"),
    ("orientation_time", r"\b(what day|what time|date today|which day|what year|what month)\b"),
    ("orientation_place", r"\b(where am i|go home|whose house|this place)\b"),
    ("today_schedule", r"\b(today|schedule|plan|appointment|next)\b"),
    ("who_is_person", r"\bwho is\b"),
    ("feeling", r"\b(feel|feeling|sad|lonely|scared|happy|tired|worried)\b"),
]


def rule_baseline(text):
    t = text.lower()
    for intent, pattern in RULES:
        if re.search(pattern, t):
            return intent
    return "out_of_scope"


class MiniLMEncoder:
    """all-MiniLM-L6-v2 exactly as sentence-transformers runs it (transformer -> mean pooling over real
    tokens -> L2 normalisation), with plain transformers: no sentence-transformers/datasets/pyarrow at runtime."""

    def __init__(self, name=None):
        import torch
        from transformers import AutoModel, AutoTokenizer
        self.torch = torch
        self.name = name or config.SENTENCE_ENCODER
        self.tok = AutoTokenizer.from_pretrained(self.name)
        self.model = AutoModel.from_pretrained(self.name).eval()

    def encode(self, texts, batch_size=64):
        texts = list(texts)
        out = []
        for i in range(0, len(texts), batch_size):
            enc = self.tok(texts[i:i + batch_size], padding=True, truncation=True, max_length=256, return_tensors="pt")
            with self.torch.no_grad():
                h = self.model(**enc).last_hidden_state
            mask = enc["attention_mask"].unsqueeze(-1).to(h.dtype)
            pooled = (h * mask).sum(1) / mask.sum(1).clamp(min=1e-9)
            out.append(self.torch.nn.functional.normalize(pooled, p=2, dim=1).numpy())
        return np.concatenate(out) if out else np.zeros((0, 384), dtype=np.float32)


class IntentModel:
    """Multinomial logistic regression stored as plain arrays (weights.npz, no pickle), so a model
    downloaded from the Hub can't execute code when loaded."""

    def __init__(self, path=None):
        self.path = Path(path) if path else models.local_dir(config.INTENT_MODEL)
        self.meta = json.loads((self.path / "meta.json").read_text())
        w = np.load(self.path / "weights.npz", allow_pickle=False)
        self.coef, self.intercept, self.classes = w["coef"], w["intercept"], w["classes"].astype(str)
        self.encoder = MiniLMEncoder(self.meta["encoder"])

    def proba(self, emb):
        z = emb @ self.coef.T + self.intercept
        z = np.exp(z - z.max(axis=1, keepdims=True))
        return z / z.sum(axis=1, keepdims=True)

    def predict(self, texts):
        single = isinstance(texts, str)
        texts = [texts] if single else list(texts)
        probs = self.proba(self.encoder.encode(texts))
        out = []
        for p in probs:
            i = int(np.argmax(p))
            label, conf = str(self.classes[i]), float(p[i])
            if conf < self.meta["oos_threshold"]:
                label = "out_of_scope"
            out.append({"intent": label, "confidence": round(conf, 4)})
        return out[0] if single else out


_lock = threading.Lock()
_model = None


def model():
    global _model
    with _lock:
        if _model is None:
            path = models.local_dir(config.INTENT_MODEL)
            if not (path / "meta.json").exists():
                raise FileNotFoundError("intent model not found; run training/train_intent.py")
            _model = IntentModel(path)
        return _model


def classify(text):
    """Intent for one utterance; falls back to keyword rules (marked as such) if the model is missing."""
    try:
        r = model().predict(text)
        r["model"] = "minilm-logreg"
    except FileNotFoundError:
        r = {"intent": rule_baseline(text), "confidence": None, "model": "rules-fallback"}
    return r
